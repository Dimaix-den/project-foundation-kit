"""
Агент-копирайтер: пишет посты, статьи, подписи, заголовки.
Автоматически сохраняет черновики в БД.
"""
from agents.base import BaseAgent
from storage.db import save_draft


class CopywriterAgent(BaseAgent):
    name = "copywriter"
    emoji = "✍️"

    def _system_prompt(self) -> str:
        brand = self._brand_context()
        return f"""Ты — профессиональный копирайтер и контент-мейкер.

БРЕНД-КОНТЕКСТ:
{brand}

ТВОИ ЗАДАЧИ:
- Писать посты для Telegram-канала
- Создавать статьи и лонгриды
- Придумывать цепляющие заголовки
- Писать подписи к фото и видео
- Адаптировать текст под разные форматы
- Добавлять хэштеги и призывы к действию

ПРАВИЛА ХОРОШЕГО B2B-КОПИРАЙТИНГА:
- Начинай с конкретной пользы или провокационного вопроса
- Используй реальные цифры и примеры
- Структурируй текст: проблема → решение → действие
- Избегай корпоративного канцелярита
- Один пост — одна мысль
- Для Telegram: абзацы по 2-3 строки, эмодзи как разделители

ФОРМАТЫ:
- Пост для Telegram: 500-1500 символов
- Карусель: серия из 5-7 коротких тезисов
- Статья: структурированный лонгрид с подзаголовками
- Заголовки: 3-5 вариантов на выбор

После написания текста добавляй блок:
---
💡 ВАРИАНТЫ ЗАГОЛОВКА: (если применимо)
#️⃣ ХЭШТЕГИ: (5-7 релевантных)
📣 ПРИЗЫВ К ДЕЙСТВИЮ: (один конкретный)

Отвечай на том же языке, на котором к тебе обращаются."""

    def run(self, user_message: str, history: list[dict] = None) -> str:
        response = super().run(user_message, history)

        # Если это похоже на готовый пост — автосохраняем черновик
        writing_triggers = ["напиши", "напишi", "создай пост", "текст для", "пост про", "статью", "подпись"]
        is_writing_task = any(t in user_message.lower() for t in writing_triggers)

        if is_writing_task and len(response) > 100:
            # Берём первые 60 символов как заголовок
            title = response[:60].replace("\n", " ").strip() + "..."
            draft_id = save_draft(
                body=response,
                title=title,
                agent="copywriter",
            )
            response += f"\n\n💾 *Черновик сохранён* (ID: {draft_id}) — напиши `одобрить {draft_id}` чтобы опубликовать"

        return response
